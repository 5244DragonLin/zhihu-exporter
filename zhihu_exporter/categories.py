def _build_override_index():
    """将 MANUAL_OVERRIDES 按匹配键类型预拆分为三个索引（模块加载时构建一次）。

    Returns:
        tuple: (问题ID字典, [(链接, 领域), ...], [(标题子串, 领域), ...])
    """
    ids, links, titles = {}, [], []
    for key, category in MANUAL_OVERRIDES.items():
        key = key.strip()
        if not key:
            continue
        if key.isdigit():  # 写法1：问题ID
            ids[key] = category
        elif "zhihu.com/question" in key:  # 写法2：完整问题链接
            links.append((key, category))
        else:  # 写法3：问题标题子串
            titles.append((key, category))
    return ids, links, titles

_OVERRIDE_IDS, _OVERRIDE_LINKS, _OVERRIDE_TITLES = _build_override_index()


def _match_override(question_url, question_title):
    """在手动覆盖表中查找该问题指定的领域，未命中返回 None。

    Args:
        question_url: 问题链接（可为空）
        question_title: 问题标题（可为空）
    """
    if question_url:
        m = re.search(r"/question/(\d+)", question_url)
        if m and m.group(1) in _OVERRIDE_IDS:
            return _OVERRIDE_IDS[m.group(1)]
    for key, category in _OVERRIDE_LINKS:
        if question_url and (key == question_url or key in question_url):
            return category
    for key, category in _OVERRIDE_TITLES:
        if question_title and key in question_title:
            return category
    return None


def classify_tags(tags, question_url=None, question_title=None):
    """将标签列表归并为领域大类。

    优先级：手动覆盖表 > 标签关键词匹配 > 兜底。
    手动覆盖按问题（链接/ID/标题）精确指定领域，未指定时才走标签匹配。

    Args:
        tags: 标签字符串列表（可为空）
        question_url: 问题链接（可选，用于手动覆盖匹配）
        question_title: 问题标题（可选，用于手动覆盖匹配）

    Returns:
        str: 领域名（"两性与婚恋" / ... / "其他" / "未分类"）
    """
    override = _match_override(question_url, question_title)
    if override:
        return override
    if not tags:
        return "未分类"
    joined = "、".join(tags).lower()
    for category, keywords in CATEGORY_KEYWORDS.items():
        if category == "其他":
            continue
        for kw in keywords:
            if kw in joined:
                return category
    return "其他"


def split_tags(tag_text):
    """将"标签：xxx、yyy"文本拆成标签列表（空文本返回空列表）"""
    if not tag_text:
        return []
    return [t.strip() for t in tag_text.split("、") if t.strip()]
